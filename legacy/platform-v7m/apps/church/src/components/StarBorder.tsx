import React from 'react';

interface StarBorderOwnProps<T extends React.ElementType> {
  as?: T;
  className?: string;
  children?: React.ReactNode;
  color?: string;
  speed?: React.CSSProperties['animationDuration'];
  thickness?: number;
  innerClassName?: string;
  style?: React.CSSProperties;
}

type StarBorderProps<T extends React.ElementType> = StarBorderOwnProps<T> &
  Omit<React.ComponentPropsWithoutRef<T>, keyof StarBorderOwnProps<T>>;

const StarBorder = <T extends React.ElementType = 'button'>({
  as,
  className = '',
  color = 'white',
  speed = '6s',
  thickness = 1,
  innerClassName = '',
  children,
  style,
  ...rest
}: StarBorderProps<T>) => {
  const Component: React.ElementType = as || 'button';

  return (
    <Component
      className={`relative inline-block overflow-hidden rounded-[20px] ${className}`}
      {...rest}
      style={{
        padding: `${thickness}px 0`,
        ...style,
      }}
    >
      <div
        className="absolute w-[300%] h-[50%] opacity-70 bottom-[-11px] right-[-250%] rounded-full animate-star-movement-bottom z-0"
        style={{
          background: `radial-gradient(circle, ${color}, transparent 10%)`,
          animationDuration: speed
        }}
      ></div>
      <div
        className="absolute w-[300%] h-[50%] opacity-70 top-[-10px] left-[-250%] rounded-full animate-star-movement-top z-0"
        style={{
          background: `radial-gradient(circle, ${color}, transparent 10%)`,
          animationDuration: speed
        }}
      ></div>
      <div
        className={`star-border-inner relative z-1 border border-gray-800 text-center rounded-[20px] ${innerClassName}`}
      >
        {children}
      </div>
    </Component>
  );
};

export default StarBorder;

